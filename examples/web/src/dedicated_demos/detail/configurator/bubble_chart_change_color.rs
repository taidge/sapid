use glory::prelude::*;
use sapid::charts::*;
fn points() -> PlotData {
    PlotData::Points(vec![
        PointDatum {
            key: "north".into(),
            label: "North".into(),
            x: 1.,
            y: 3.,
            size: 1.,
        },
        PointDatum {
            key: "south".into(),
            label: "South".into(),
            x: 4.,
            y: 2.,
            size: 4.,
        },
        PointDatum {
            key: "west".into(),
            label: "West".into(),
            x: 2.,
            y: 5.,
            size: 9.,
        },
        PointDatum {
            key: "east".into(),
            label: "East".into(),
            x: 5.,
            y: 4.,
            size: 3.,
        },
    ])
}
fn sample_data() -> PlotData {
    points()
}

pub fn demo(theme: sapid::Theme) -> impl Widget {
    widget(move |scope| {
        let color = scope.cage("Blue".to_owned());
        let base = theme.clone();
        let options = scope.bond(move || PlotOptions {
            ..Default::default()
        });
        let palette = scope.bond(move || {
            let mut palette = controls::chart_palette(&base);
            palette.series[0] = controls::accent(base.clone(), &color.get()).accent;
            palette
        });
        let preview = plot("bubble-chart-change-color", PlotKind::Bubble)
            .theme(theme.clone())
            .chart_theme(palette)
            .options(options)
            .frame(ChartFrame {
                width: 320.,
                height: 320.,
            })
            .data(sample_data())
            .legend(false)
            .data_table(false)
            .navigation(false)
            .style(scope.bond(move || {
                Style::new()
                    .width(Length::Px(200.))
                    .max_width(Limit::Percent(100.))
            }));
        view()
            .class("site-configurator site-chart-configurator site-compact-plot")
            .fill(controls::playground(
                Box::new(preview),
                vec![controls::named_color_choices(
                    "bubble-chart-change-color-color",
                    "Color",
                    color.into(),
                    move |next| color.revise(|current| *current = next),
                    &theme,
                )],
            ))
            .show_in(scope)
    })
}
